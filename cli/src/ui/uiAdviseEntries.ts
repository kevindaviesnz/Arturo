/**
 * Interactive "business adviser" onboarding for `/enterprise create --advise`.
 *
 * This is a real back-and-forth conversation, not a fixed questionnaire: every
 * Arturo turn is generated by the model from the conversation so far, so it can
 * react to what the operator just said before deciding what to ask next. There
 * is no "Question N of M" framing after the opening turn — it should read like
 * talking to an adviser. The conversation is bounded (at least MIN, at most MAX
 * answers) and the model may end it early by ending a turn with the word READY,
 * which is stripped before display.
 *
 * The Enterprise's name is optional up front. If omitted, the operator is never
 * asked for one directly during the conversation — once Arturo has enough
 * understanding to conclude, it proposes a name based on everything discussed,
 * which the operator accepts, declines (to be asked again), or overrides with
 * their own. Only once a name is resolved is the Enterprise created — with a
 * mission drawn from the operator's answers — and the existing `/next` guidance
 * staged to recommend Business Functions. Abandoning the conversation
 * ("cancel"), at any point including during naming, leaves nothing behind.
 */

type ConversationTurn = {
  readonly role: "assistant" | "user";
  readonly content: string;
};

type PendingNameConfirmation = {
  readonly suggestedName?: string;
};

type AdviseSession = {
  readonly name: string | undefined;
  readonly transcript: ConversationTurn[];
  pendingNameConfirmation?: PendingNameConfirmation;
  lastShownMessage: string;
};

let activeAdviseSession:
  | AdviseSession
  | undefined;

/** Bounds on the number of operator answers in the conversation. */
export const MIN_ADVISE_ANSWERS = 3;
export const MAX_ADVISE_ANSWERS = 5;

/** Replies that end the interview on the operator's say-so, not the model's. */
const OPERATOR_END_INTENTS: ReadonlySet<OperatorTurnIntent> = new Set([
  "complete",
  "pushback",
]);

/** Used only if the model is unavailable when opening the conversation. */
const FALLBACK_OPENING_MESSAGE =
  "Hi, I'm Arturo. I'll help you think through how to set this up — in your own words, what kind of work do you do, or want to do?";

/** Used only if the model returns an empty reply mid-conversation. */
const FALLBACK_CONTINUATION_MESSAGE =
  "Sorry, could you say a bit more about that?";

/** Used only if the naming/closing call fails or the model is unavailable. */
const FALLBACK_CLOSING_MESSAGE =
  "Thanks — I have a good picture of the business now.";

const CANCEL_WORDS = new Set([
  "cancel",
  "stop",
  "quit",
  "exit",
]);

/** Returns the active advise session, if any. */
export function getActiveAdviseSession():
  | AdviseSession
  | undefined {
  return activeAdviseSession;
}

/** Ends any active advise session. */
export function endAdviseSession(): void {
  activeAdviseSession = undefined;
}

function answerCount(
  transcript: readonly ConversationTurn[]
): number {
  return transcript.filter(
    (turn) => turn.role === "user"
  ).length;
}

function formatTranscriptForPrompt(
  transcript: readonly ConversationTurn[]
): string {
  if (transcript.length === 0) {
    return "(the conversation has not started yet)";
  }

  return transcript
    .map(
      (turn) =>
        `${turn.role === "assistant" ? "Arturo" : "Operator"}: ${turn.content}`
    )
    .join("\n");
}

/**
 * The operator's own account of their business, for storage and for `/next`.
 *
 * The Enterprise description used to hold `formatTranscriptForPrompt` output —
 * a *prompt* helper — so `/enterprise inspect` rendered "Arturo:" and
 * "Operator:" as though they were fields of the record. Arturo's own questions
 * are not part of the operator's account of their business, and keeping them
 * made the field unreadable in the one place it is shown.
 *
 * PURE: No side effects.
 */
export function formatOperatorAccount(
  transcript: readonly ConversationTurn[]
): string {
  return transcript
    .filter((turn) => turn.role === "user")
    .map((turn) => turn.content.trim())
    .filter(Boolean)
    .join("\n");
}

/** Builds the prompt asking the model for Arturo's next conversational turn. */
export function buildAdviserConversationPrompt(
  name: string | undefined,
  transcript: readonly ConversationTurn[]
): string {
  const answered =
    answerCount(
      transcript
    );

  const lastOperatorTurn =
    [...transcript]
      .reverse()
      .find((turn) => turn.role === "user")?.content ?? "";
  const intentInstruction =
    transcript.length > 0
      ? instructionForOperatorTurn(
          classifyOperatorTurn(
            lastOperatorTurn
          ),
          answered >= MIN_ADVISE_ANSWERS
        )
      : undefined;

  const instruction =
    intentInstruction ??
    (transcript.length === 0
      ? "Start the conversation: greet them warmly in one short sentence, introduce yourself briefly as their adviser, then ask what kind of work they do or want to do. Do not assume they already have a running business — they may just be starting out or still thinking it through."
      : answered < MIN_ADVISE_ANSWERS
        ? "Continue the conversation: react briefly and specifically to what they just said, then ask the next question that would most help you understand the business. Ask about one thing at a time."
        : "Continue the conversation: react briefly and specifically to what they just said. If you now understand enough about who the business serves, what it does, and where a person needs to stay in control, say so warmly in a sentence or two and then end your reply on its own final line with exactly: READY. Otherwise, ask one more useful question.");

  const framing =
    name
      ? `You are Arturo, a warm, plain-language business adviser. You are getting to know a new or planned business called "${name}" so you can recommend how to organise its ongoing work. It may already be running, or they may just be starting out.`
      : "You are Arturo, a warm, plain-language business adviser. You are getting to know a new or planned business (it doesn't have a name yet) so you can recommend how to organise its ongoing work. It may already be running, or they may just be starting out.";

  // A question or a complaint gets its own compact prompt. Left inside the full
  // interview framing, the instruction to answer first was reliably ignored by
  // a small local model, which is how the operator got asked another question
  // twice in a row after challenging the adviser directly.
  if (intentInstruction) {
    return renderEnterprisePrompt("Business Discovery Conversation Reply", {
    ADVISER_FRAMING: framing,
    TRANSCRIPT: formatTranscriptForPrompt(
        transcript
      ),
    REPLY_INSTRUCTION: intentInstruction
  });
  }

  return renderEnterprisePrompt("Business Discovery Conversation Interview", {
    ADVISER_FRAMING: framing,
    TRANSCRIPT: formatTranscriptForPrompt(
      transcript
    ),
    REPLY_INSTRUCTION: instruction
  });
}

/** Strips a trailing standalone "READY" line, reporting whether it was present. */
export function extractReadyMarker(
  raw: string
): { readonly message: string; readonly ready: boolean } {
  const trimmed =
    raw.trim();
  const lines =
    trimmed.split("\n");
  const lastLine =
    (lines[lines.length - 1] ?? "").trim();

  if (
    /^ready[.!]?$/i.test(
      lastLine
    )
  ) {
    return {
      message: lines.slice(0, -1).join("\n").trim(),
      ready: true,
    };
  }

  return {
    message: trimmed,
    ready: false,
  };
}

/** Strips a trailing standalone "NAME: <suggestion>" line, extracting the name. */
export function extractNameSuggestion(
  raw: string
): { readonly message: string; readonly suggestedName?: string } {
  const trimmed =
    raw.trim();
  const lines =
    trimmed.split("\n");
  const lastLine =
    (lines[lines.length - 1] ?? "").trim();
  const match =
    /^name\s*:\s*(.+)$/i.exec(
      lastLine
    );

  if (match) {
    // A walkthrough was offered `Reply "yes" to call it "Community Table
    // Auckland —"`: the model ended its NAME line with a dangling em dash and
    // only quotes were being stripped, so the punctuation would have become
    // part of the Enterprise's name. Trim the leading bullet and the trailing
    // sentence punctuation a model reaches for, then the quotes again.
    const suggested =
      match[1]
        .trim()
        .replace(/^["'`]+|["'`]+$/g, "")
        .replace(/^[-–—*•\s]+/, "")
        .replace(/[-–—,;:.\s]+$/, "")
        .replace(/^["'`]+|["'`]+$/g, "")
        .trim();

    return {
      message: lines.slice(0, -1).join("\n").trim(),
      suggestedName:
        suggested.length > 0
          ? suggested
          : undefined,
    };
  }

  return {
    message: trimmed,
    suggestedName: undefined,
  };
}

export type AdviserTurnOutcome = {
  readonly done: boolean;
  readonly message: string;
};

/**
 * Asks the model for Arturo's next conversational turn given the transcript so
 * far. The model may only end the conversation (`done: true`) once at least
 * MIN_ADVISE_ANSWERS answers have been given, regardless of what it says.
 *
 * SIDE EFFECT: Calls the configured LLM provider.
 */
export async function generateNextAdviserTurn(
  name: string | undefined,
  transcript: readonly ConversationTurn[]
): Promise<AdviserTurnOutcome> {
  const result =
    await generateWithConfiguredLlm({
      model: resolveNextStepModel(process.env),
      prompt: buildAdviserConversationPrompt(
        name,
        transcript
      ),
    });

  const { message, ready } =
    extractReadyMarker(
      result.response
    );

  const done =
    ready &&
    answerCount(transcript) >= MIN_ADVISE_ANSWERS;

  return {
    done,
    message:
      message.length > 0
        ? message
        : FALLBACK_CONTINUATION_MESSAGE,
  };
}

/** Builds the prompt asking the model to wrap up and suggest a name. */
export function buildClosingWithNameSuggestionPrompt(
  transcript: readonly ConversationTurn[]
): string {
  return renderEnterprisePrompt("Business Name Suggestion", {
    TRANSCRIPT: formatTranscriptForPrompt(
      transcript
    )
  });
}

export type ClosingWithNameOutcome = {
  readonly message: string;
  readonly suggestedName?: string;
};

/**
 * Asks the model for a closing message and a suggested Enterprise name, based
 * on the full conversation. Used only when the operator did not supply a name.
 *
 * SIDE EFFECT: Calls the configured LLM provider.
 */
export async function generateClosingWithNameSuggestion(
  transcript: readonly ConversationTurn[]
): Promise<ClosingWithNameOutcome> {
  const result =
    await generateWithConfiguredLlm({
      model: resolveNextStepModel(process.env),
      prompt: buildClosingWithNameSuggestionPrompt(
        transcript
      ),
    });

  const { message, suggestedName } =
    extractNameSuggestion(
      result.response
    );

  return {
    message:
      message.length > 0
        ? message
        : FALLBACK_CLOSING_MESSAGE,
    suggestedName,
  };
}

/**
 * Starts a guided advise conversation and returns Arturo's opening turn. Does
 * not create the Enterprise yet. The Enterprise name is optional — when
 * omitted, Arturo will propose one once the conversation concludes.
 *
 * SIDE EFFECT:
 * - Sets the module-level active advise session.
 * - Calls the configured LLM provider for the opening turn.
 */
export async function startAdviseSession(
  name?: string
): Promise<WorkStreamEntry> {
  let opening = FALLBACK_OPENING_MESSAGE;

  try {
    const outcome =
      await generateNextAdviserTurn(
        name,
        []
      );
    opening = outcome.message;
  } catch {
    // Fall back to the fixed opener if the model is unavailable.
  }

  const body =
    [
      opening,
      "",
      '(Answer in plain text, or type "cancel" to stop.)',
    ].join("\n");

  activeAdviseSession = {
    name,
    transcript: [
      { role: "assistant", content: opening },
    ],
    lastShownMessage: body,
  };

  return {
    actor: "Arturo",
    label: "Guided setup",
    body,
  };
}

/**
 * Builds a mission (adviser context) and a full transcript description.
 *
 * The mission is synthesised by the model so it reads as a statement of what
 * the business does, rather than a transcript of replies. Synthesis failure
 * falls back to the joined answers: an imperfect mission is editable with
 * /enterprise update, a failed Enterprise creation is not.
 *
 * SIDE EFFECT: Calls the configured LLM provider.
 */
async function synthesiseEnterpriseContext(
  name: string,
  transcript: readonly ConversationTurn[]
): Promise<{ mission: string; description: string }> {
  const description =
    formatOperatorAccount(
      transcript
    );

  // Two attempts, because the fallback is the raw joined answers — readable but
  // not a mission. A rejected mission is usually one invented detail away from
  // being fine, so it is worth asking again before giving up on synthesis.
  for (let attempt = 1; attempt <= 2; attempt += 1) {
    try {
      const { response } =
        await generateWithConfiguredLlm({
          model: resolveNextStepModel(),
          prompt: buildMissionSynthesisPrompt(
            name,
            transcript
          ),
        });

      return {
        mission: parseSynthesisedMission(
          response,
          transcript
        ),
        description,
      };
    } catch {
      continue;
    }
  }

  return {
    mission: joinAnswersAsMission(
      transcript
    ),
    description,
  };
}

/** Creates the Enterprise with the resolved name, hands off to /next guidance, and clears the session. */
async function finishAdviseSession(
  session: AdviseSession,
  name: string,
  closingMessage?: string
): Promise<readonly WorkStreamEntry[]> {
  const { transcript } = session;
  const { mission, description } =
    await synthesiseEnterpriseContext(
      name,
      transcript
    );

  endAdviseSession();

  const enterprise =
    createAndSaveEnterprise({
      name,
      mission,
      description,
    });

  const advice =
    await handleUiNextCommand([
      enterprise.name,
    ]);

  return [
    {
      actor: "Arturo",
      label: "Guided setup",
      body: [
        closingMessage?.trim() ||
          `Thanks — I have a good picture of "${name}" now. I've created the Enterprise with a mission drawn from what you told me.`,
        "",
        "Here's what I'd recommend for how to organise it:",
      ].join("\n"),
    },
    advice,
  ];
}

/**
 * Removes a name proposal left stranded in the closing prose.
 *
 * The suggestion is only offered when the model ends its reply with a NAME:
 * line. When it writes the proposal into the prose instead — "I think a fitting
 * name for your business would be Auckland Family Pantry —" — there is nothing
 * to accept, so Arturo asks the open question underneath it and the two read as
 * a contradiction. Drop the stranded sentence rather than the whole message.
 *
 * PURE: No side effects.
 */
export function stripDanglingNameProposal(
  message: string
): string {
  const kept =
    message
      .split(/(?<=[.!?])\s+/)
      .filter(
        (sentence) =>
          !/\bnames?\b|\bnamed\b|\bcall(?:ed|ing)?\s+(?:it|this|them|your)\b/i.test(
            sentence
          )
      )
      .join(" ")
      .trim();

  return kept.length > 0
    ? kept
    : FALLBACK_CLOSING_MESSAGE;
}

/**
 * Ends the conversation when the operator did not supply a name: asks the model
 * for a closing message and a suggested name, then stages the naming
 * confirmation step. Falls back to a deterministic request for a name if the
 * model does not produce a usable suggestion, or is unavailable.
 *
 * SIDE EFFECT: Calls the configured LLM provider.
 */
async function beginNamingConfirmation(
  session: AdviseSession
): Promise<readonly WorkStreamEntry[]> {
  let closing: ClosingWithNameOutcome;

  try {
    closing =
      await generateClosingWithNameSuggestion(
        session.transcript
      );
  } catch {
    closing = {
      message: FALLBACK_CLOSING_MESSAGE,
      suggestedName: undefined,
    };
  }

  session.pendingNameConfirmation = {
    suggestedName: closing.suggestedName,
  };

  const body =
    closing.suggestedName
      ? [
          closing.message,
          "",
          `Reply "yes" to call it "${closing.suggestedName}", or tell me what you'd prefer instead.`,
        ].join("\n")
      : [
          stripDanglingNameProposal(
            closing.message
          ),
          "",
          "One last thing — what would you like to call this business?",
        ].join("\n");

  session.lastShownMessage = body;

  return [
    {
      actor: "Arturo",
      label: "Guided setup",
      body,
    },
  ];
}

/** Resolves a reply given while a name suggestion is pending confirmation. */
async function resolvePendingNameConfirmation(
  session: AdviseSession,
  reply: string
): Promise<readonly WorkStreamEntry[]> {
  const pending =
    session.pendingNameConfirmation;

  if (
    pending?.suggestedName &&
    isAffirmative(reply)
  ) {
    return finishAdviseSession(
      session,
      pending.suggestedName
    );
  }

  if (
    pending?.suggestedName &&
    isNegative(reply)
  ) {
    session.pendingNameConfirmation = {
      suggestedName: undefined,
    };

    const body =
      "No problem — what would you like to call it instead?";
    session.lastShownMessage = body;

    return [
      {
        actor: "Arturo",
        label: "Guided setup",
        body,
      },
    ];
  }

  // A reply that reads as a sentence is interpreted and confirmed rather than
  // stored verbatim: "It's already called Marlowe Books" is an answer, not a
  // company name, and there is no way back once the wrong one is recorded.
  const interpreted =
    interpretEnterpriseNameReply(
      reply
    );

  if (interpreted.kind === "name") {
    return finishAdviseSession(
      session,
      interpreted.name
    );
  }

  // A failed interpretation must not destroy the standing suggestion: wiping
  // it silently killed the advertised "yes" option, leaving a re-prompt loop
  // with no way out except guessing the expected format.
  session.pendingNameConfirmation = {
    suggestedName:
      interpreted.candidate ||
      pending?.suggestedName ||
      undefined,
  };

  const body =
    formatNameConfirmationPrompt(
      interpreted.candidate,
      pending?.suggestedName
    );
  session.lastShownMessage = body;

  return [
    {
      actor: "Arturo",
      label: "Guided setup",
      body,
    },
  ];
}

/**
 * Routes a plain-text reply to the active advise session, when present. Returns
 * undefined when no session is active so the caller can fall through to other
 * continuations (e.g. Worker Chat).
 *
 * SIDE EFFECT:
 * - Advances / clears the module-level advise session.
 * - Calls the configured LLM provider for Arturo's next conversational turn, and,
 *   once the conversation ends without a known name, for a name suggestion.
 * - On completion: creates the Enterprise and runs the /next guidance.
 */
export async function handleUiAdviseContinuation(
  response: string
): Promise<readonly WorkStreamEntry[] | undefined> {
  const session =
    activeAdviseSession;

  if (!session) {
    return undefined;
  }

  const trimmed =
    response.trim();

  if (
    CANCEL_WORDS.has(
      trimmed.toLowerCase()
    )
  ) {
    endAdviseSession();
    return [
      {
        actor: "Arturo",
        label: "Guided setup cancelled",
        body: 'No Enterprise was created. Start again any time with /enterprise create "<name>" --advise.',
      },
    ];
  }

  if (trimmed.length === 0) {
    return [
      {
        actor: "Arturo",
        label: "Guided setup",
        body: session.lastShownMessage,
      },
    ];
  }

  if (session.pendingNameConfirmation) {
    return resolvePendingNameConfirmation(
      session,
      trimmed
    );
  }

  session.transcript.push({
    role: "user",
    content: trimmed,
  });

  const answered =
    answerCount(session.transcript);

  // Telling the model to stop is not the same as stopping. A walkthrough said
  // "That's about it really. Can we get started?", got a warm "Thank you for
  // sharing all that with me" with no READY marker, and was asked about
  // reporting again — so their next line, the actual name of their
  // organisation, was swallowed as an interview answer and the adviser went on
  // to propose a different name for their own charity.
  //
  // The classification is Arturo's, so the ending is Arturo's too. The minimum
  // still applies: below it there is not enough to build a mission from.
  const operatorEndedIt =
    answered >= MIN_ADVISE_ANSWERS &&
    OPERATOR_END_INTENTS.has(
      classifyOperatorTurn(
        trimmed
      )
    );

  const shouldEnd =
    answered >= MAX_ADVISE_ANSWERS ||
    operatorEndedIt;

  if (session.name !== undefined) {
    // Name already known: unaffected by naming — no extra model call beyond the
    // regular per-turn call.
    const name =
      session.name;

    if (shouldEnd) {
      return finishAdviseSession(
        session,
        name
      );
    }

    try {
      const outcome =
        await generateNextAdviserTurn(
          name,
          session.transcript
        );

      if (outcome.done) {
        return finishAdviseSession(
          session,
          name,
          outcome.message
        );
      }

      session.transcript.push({
        role: "assistant",
        content: outcome.message,
      });
      session.lastShownMessage =
        outcome.message;

      return [
        {
          actor: "Arturo",
          label: "Guided setup",
          body: outcome.message,
        },
      ];
    } catch {
      // If the model is unavailable, finish with what we have rather than stall.
      return finishAdviseSession(
        session,
        name
      );
    }
  }

  // Name unknown: ending the conversation always goes through naming
  // confirmation, whether triggered by READY or by the MAX-answers cap.
  if (shouldEnd) {
    return beginNamingConfirmation(
      session
    );
  }

  try {
    const outcome =
      await generateNextAdviserTurn(
        session.name,
        session.transcript
      );

    if (outcome.done) {
      return beginNamingConfirmation(
        session
      );
    }

    session.transcript.push({
      role: "assistant",
      content: outcome.message,
    });
    session.lastShownMessage =
      outcome.message;

    return [
      {
        actor: "Arturo",
        label: "Guided setup",
        body: outcome.message,
      },
    ];
  } catch {
    // If the model is unavailable, move straight to naming confirmation, which
    // itself falls back gracefully if the model is still unavailable.
    return beginNamingConfirmation(
      session
    );
  }
}
