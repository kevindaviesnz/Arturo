/**
 * Purpose: Creates usage text for /runtime.
 *
 * Params:
 * - None.
 *
 * Returns:
 * - Runtime command usage text.
 *
 * PURE: No side effects.
 */
export function createRuntimeUsageText(): string {
  return [
    "Usage:",
    '  /job start "<job-name-or-id>" [--enterprise "<enterprise-name-or-id>"]',
    '  /job inspect "<job-name-or-id>" [--enterprise "<enterprise-name-or-id>"]',
  ].join("\n");
}

/**
 * Purpose: Creates a deterministic runtime id for a business function.
 *
 * Params:
 * - businessFunctionId: Business function definition id.
 *
 * Returns:
 * - Runtime id.
 *
 * PURE: No side effects.
 */
export function createRuntimeId(
  businessFunctionId: string
): string {
  return `${businessFunctionId}:runtime-1`;
}

/**
 * Purpose: Formats a runtime state for Chapter 5 output.
 *
 * Params:
 * - state: Runtime state.
 *
 * Returns:
 * - Human-readable state.
 *
 * PURE: No side effects.
 */
export function formatRuntimeState(
  state: string
): string {
  return state
    .slice(
      0,
      1
    )
    .toUpperCase() +
    state.slice(
      1
    );
}

/**
 * Purpose: Creates a default runtime objective for a business function.
 *
 * Params:
 * - definition: Business function definition.
 *
 * Returns:
 * - Runtime objective.
 *
 * PURE: No side effects.
 */
export function createRuntimeObjective(
  definition: BusinessFunctionDefinition
): string {
  if (definition.objective.trim().length > 0) {
    return definition.objective;
  }

  return `Continuously pursue ${definition.label}.`;
}

/**
 * Purpose: Counts distinct workers assigned to Jobs generated by a runtime.
 *
 * Params:
 * - runtime: Business function runtime.
 *
 * Returns:
 * - Number of distinct workers assigned to runtime-generated Jobs.
 *
 * SIDE EFFECT:
 * - Reads Job queue.
 */
export function countAssignedWorkers(
  runtime: BusinessFunctionRuntime
): number {
  const assignedWorkers =
    runtime.jobIds
      .map(
        getJob
      )
      .map(
        (job) =>
          job?.worker
      )
      .filter(
        (worker): worker is string =>
          typeof worker === "string" &&
          worker.trim().length > 0
      );

  return new Set(
    assignedWorkers
  ).size;
}

/**
 * Purpose: Formats Chapter 5 runtime start output.
 *
 * Params:
 * - runtime: Started runtime.
 *
 * Returns:
 * - Human-readable runtime start output.
 *
 * PURE: No side effects.
 */
export function formatRuntimeStarted(
  runtime: BusinessFunctionRuntime
): string {
  return [
    "✓ Function started",
    "",
    "Function:",
    `  ${runtime.label}`,
    "",
    "State:",
    `  ${formatRuntimeState(runtime.state)}`,
    "",
    "Tasks:",
    `  ${runtime.jobIds.length}`,
    "",
    "Health:",
    "  Unknown",
  ].join("\n");
}

/**
 * Purpose: Formats Chapter 5 runtime inspection output.
 *
 * Params:
 * - definition: Business function definition.
 * - runtime: Runtime to inspect.
 *
 * Returns:
 * - Human-readable runtime detail.
 *
 * PURE: No side effects.
 */
export function formatRuntimeDetail(
  definition: BusinessFunctionDefinition,
  runtime: BusinessFunctionRuntime
): string {
  const runtimeEvents = listRuntimeEventStore().filter((event) => {
    const payload = event.payload;

    return typeof payload === "object" &&
      payload !== null &&
      "runtimeId" in payload &&
      payload.runtimeId === runtime.id;
  });
  const signalsEvaluated =
    runtimeEvents.filter((event) => {
      if (
        event.type !== "runtime.signal.evaluated" &&
        event.type !== "runtime.signal.evaluation_failed"
      ) {
        return false;
      }

      return true;
    }).length;
  const outcomesMeasured = runtimeEvents.filter(
    (event) => event.type === "runtime.outcome.measured"
  );
  const latestOutcome =
    outcomesMeasured.at(-1);
  const latestPayload =
    latestOutcome?.payload;
  const health =
    typeof latestPayload === "object" &&
    latestPayload !== null &&
    "health" in latestPayload &&
    typeof latestPayload.health === "string"
      ? latestPayload.health
      : undefined;
  const healthReport = evaluateBusinessFunctionHealth(definition);
  const retainedLessons = listOperationalMemory(runtime.id).filter(
    isRetainedOperationalLesson
  );

  return [
    `Function: ${definition.label}`,
    `  ID:                  ${definition.id}`,
    `  Operating state:     ${formatRuntimeState(runtime.state)}`,
    "",
    "  Objective:",
    `    ${runtime.objective}`,
    "",
    `  Overall Health:      ${healthReport.overallHealth} (computed)`,
    `  Latest Outcome:      ${health ? formatRuntimeState(health) : "None measured"}`,
    `  Tasks Generated:     ${runtime.jobIds.length}`,
    `  Workers Assigned:    ${countAssignedWorkers(runtime)}`,
    `  Signals Evaluated:    ${signalsEvaluated}`,
    `  Outcomes Measured:    ${outcomesMeasured.length}`,
    `  Lessons Retained:     ${retainedLessons.length}`,
    ...(
      retainedLessons.length > 0
        ? [
            "",
            "  Recent Retained Lessons:",
            ...retainedLessons.slice(-3).map(
              (lesson) => `    - ${lesson.content}`
            ),
          ]
        : []
    ),
  ].join("\n");
}

/**
 * Purpose: Starts or resumes a runtime for a business function definition.
 *
 * Params:
 * - definition: Business function definition.
 *
 * Returns:
 * - Started runtime, ready to observe organisational signals.
 *
 * SIDE EFFECT:
 * - Mutates runtime store.
 * - Mutates business function definition store.
 * - Does not create work until a signal has been evaluated.
 */
export function startRuntimeForBusinessFunction(
  definition: BusinessFunctionDefinition
): BusinessFunctionRuntime {
  const runtimeId =
    definition.runtimeId ??
    createRuntimeId(
      definition.id
    );

  const existingRuntime =
    getBusinessFunction(
      runtimeId
    );

  const startedRuntime =
    existingRuntime
      ? startBusinessFunction(
          existingRuntime
        )
      : startBusinessFunction(
          createBusinessFunctionRuntime({
            id: runtimeId,
            label: definition.label,
            objective: createRuntimeObjective(
              definition
            ),
            ownerWorker: "unassigned",
          })
        );

saveBusinessFunction(
  startedRuntime
);

attachRuntimeToBusinessFunctionDefinition(
  definition.id,
  startedRuntime.id
);

broadcastEvent(
  "runtime.started",
  "success",
  `Function started: ${startedRuntime.label}`
);

  return startedRuntime;
}

/**
 * Purpose: Resolves a runtime inspection target from function id, function label, or runtime id.
 *
 * Params:
 * - idOrLabelOrRuntimeId: Business function id, label, or runtime id.
 *
 * Returns:
 * - Matching definition/runtime pair or undefined.
 *
 * SIDE EFFECT:
 * - Reads definition and runtime stores.
 */
export function resolveRuntimeInspectionTarget(
  idOrLabelOrRuntimeId: string
):
  | {
      readonly definition: BusinessFunctionDefinition;
      readonly runtime: BusinessFunctionRuntime;
    }
  | undefined {
  const definitionByFunction =
    getBusinessFunctionDefinitionByIdOrLabel(
      idOrLabelOrRuntimeId
    );

  if (definitionByFunction?.runtimeId) {
    const runtime =
      getBusinessFunction(
        definitionByFunction.runtimeId
      );

    return runtime
      ? {
          definition: definitionByFunction,
          runtime,
        }
      : undefined;
  }

  const definitionByRuntime =
    getBusinessFunctionDefinitionByRuntimeId(
      idOrLabelOrRuntimeId
    );

  const runtime =
    getBusinessFunction(
      idOrLabelOrRuntimeId
    );

  if (!definitionByRuntime || !runtime) {
    return undefined;
  }

  return {
    definition: definitionByRuntime,
    runtime,
  };
}

/**
 * Purpose: Handles /runtime start.
 *
 * Params:
 * - args: Runtime start arguments.
 *
 * Returns:
 * - void
 *
 * SIDE EFFECT:
 * - Starts runtime.
 * - Writes terminal output.
 */
export function handleRuntimeStartCommand(
  args: readonly string[]
): void {
  const [
    idOrLabel,
  ] = args;
  const enterpriseIndex =
    args.indexOf(
      "--enterprise"
    );
  const enterpriseReference =
    enterpriseIndex >= 0
      ? args[enterpriseIndex + 1]
      : undefined;

  if (!idOrLabel) {
    console.log(
      'Usage: /runtime start "<job-name-or-id>" [--enterprise "<enterprise-name-or-id>"]'
    );

    return;
  }

  const enterprise =
    enterpriseReference
      ? getEnterpriseByIdOrName(
          enterpriseReference
        )
      : undefined;
  if (enterpriseReference && !enterprise) {
    console.log(
      `enterprise not found: ${enterpriseReference}`
    );
    return;
  }
  const definition =
    enterprise
      ? listBusinessFunctionDefinitionsByEnterprise(
          enterprise.id
        ).find(
          (candidate) =>
            candidate.id === idOrLabel ||
            candidate.label.trim().toLowerCase() ===
              idOrLabel.toLowerCase()
        )
      : getBusinessFunctionDefinitionByIdOrLabel(
          idOrLabel
        );

  if (!definition) {
    console.log(
      `function not found: ${idOrLabel}`
    );

    return;
  }

  const runtime =
    startRuntimeForBusinessFunction(
      definition
    );
  
  console.log(
    formatRuntimeStarted(
      runtime
    )
  );
}

/**
 * Purpose: Handles /runtime inspect.
 *
 * Params:
 * - args: Runtime inspect arguments.
 *
 * Returns:
 * - void
 *
 * SIDE EFFECT:
 * - Reads runtime state.
 * - Writes terminal output.
 */
export function handleRuntimeInspectCommand(
  args: readonly string[]
): void {
  const [
    idOrLabelOrRuntimeId,
  ] = args;
  const enterpriseIndex =
    args.indexOf(
      "--enterprise"
    );
  const enterpriseReference =
    enterpriseIndex >= 0
      ? args[enterpriseIndex + 1]
      : undefined;

  if (!idOrLabelOrRuntimeId) {
    console.log(
      'Usage: /runtime inspect "<job-name-or-id-or-runtime-id>" [--enterprise "<enterprise-name-or-id>"]'
    );

    return;
  }

  const enterprise =
    enterpriseReference
      ? getEnterpriseByIdOrName(
          enterpriseReference
        )
      : undefined;
  if (enterpriseReference && !enterprise) {
    console.log(
      `enterprise not found: ${enterpriseReference}`
    );
    return;
  }
  const scopedDefinition =
    enterprise
      ? listBusinessFunctionDefinitionsByEnterprise(
          enterprise.id
        ).find(
          (candidate) =>
            candidate.id ===
              idOrLabelOrRuntimeId ||
            candidate.runtimeId ===
              idOrLabelOrRuntimeId ||
            candidate.label.trim().toLowerCase() ===
              idOrLabelOrRuntimeId.toLowerCase()
        )
      : undefined;
  const target =
    scopedDefinition
      ? resolveRuntimeInspectionTarget(
          scopedDefinition.id
        )
      : enterprise
        ? undefined
        : resolveRuntimeInspectionTarget(
            idOrLabelOrRuntimeId
          );

  if (!target) {
    console.log(
      `function operating state not found: ${idOrLabelOrRuntimeId}`
    );

    return;
  }

  console.log(
    formatRuntimeDetail(
      target.definition,
      target.runtime
    )
  );
}

/**
 * Purpose: Handles /runtime commands.
 *
 * Params:
 * - args: Runtime command arguments.
 *
 * Returns:
 * - void
 *
 * SIDE EFFECT:
 * - Reads or mutates runtime state.
 * - Writes terminal output.
 */
export function handleRuntimeCommand(
  args: readonly string[]
): void {
  const [
    subcommand,
    ...subcommandArgs
  ] = args;

  switch (subcommand) {
    case "start": {
      handleRuntimeStartCommand(
        subcommandArgs
      );

      return;
    }

    case "inspect": {
      handleRuntimeInspectCommand(
        subcommandArgs
      );

      return;
    }

    default: {
      console.log(
        createRuntimeUsageText()
      );
    }
  }
}
