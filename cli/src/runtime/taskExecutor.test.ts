/** Someone who can sign off turns web search on for the business, signed in (W1). */
function webSearchOn(enterpriseId: string, configuration: WebSearchConfiguration): void {
  addWorker(createHumanWorker("Amy Wise", "guardian"));
  runtimeDb.prepare("INSERT INTO enterprise_worker_memberships VALUES(?,?,NULL)").run("Amy Wise", enterpriseId);
  const outcome = turnWebSearchOn({
    enterpriseId,
    reason: "Trend research needs current sources.",
    actor: { userId: "user-amy", workerName: "Amy Wise", displayName: "Amy Wise", roles: new Map([[enterpriseId, "owner"]]) },
    configuration,
  });
  if ("refused" in outcome) throw new Error(outcome.refused);
}

/** The web step's own signed go-ahead. */
function goAhead(jobId: string): void {
  createJobApprovalChain(jobId, 1);
  approveJobInChain(jobId, "Amy Wise");
}

