/**
 * Creates a signed approval fixture.
 *
 * @param worker Approving worker.
 * @param timestamp Decision timestamp.
 * @returns Signed approval decision.
 *
 * PURE: No side effects.
 */
function createSignedApproval(
  jobId: string,
  worker: string,
  timestamp: number
) {
  return createSignedApprovalDecision(
    {
      worker,
      decision: "approved",
      timestamp,
    },
    jobId,
    APPROVAL_SIGNING_SECRET
  );
}

/**
 * Creates a signed rejection fixture.
 *
 * @param worker Rejecting worker.
 * @param reason Rejection reason.
 * @param timestamp Decision timestamp.
 * @returns Signed rejection decision.
 *
 * PURE: No side effects.
 */
function createSignedRejection(
  jobId: string,
  worker: string,
  reason: string,
  timestamp: number
) {
  return createSignedApprovalDecision(
    {
      worker,
      decision: "rejected",
      reason,
      timestamp,
    },
    jobId,
    APPROVAL_SIGNING_SECRET
  );
}

/**
 * Creates a completed kernel-linked job for tests.
 *
 * @param rawOutput Raw job output.
 * @returns Completed job fixture.
 *
 * PURE: No side effects.
 */
function createCompletedKernelJob(
  rawOutput: string
): Job {
  return {
    id: "job-1",
    task: "Test task",
    worker: "writer",
    kernelCallId: "call-1",
    status: "completed",
    rawOutput,
    output: `Output: ${rawOutput}`,
    createdAt: 1,
    completedAt: 2,
  };
}

/**
 * Creates a completed capability job for tests.
 *
 * @param capability Capability id.
 * @param rawOutput Raw job output.
 * @returns Completed capability job fixture.
 *
 * PURE: No side effects.
 */
function createCompletedCapabilityJob(
  capability: string,
  rawOutput: string
): Job {
  return {
    ...createCompletedKernelJob(
      rawOutput
    ),
    requiredCapabilities: [
      capability as any,
    ],
  };
}

