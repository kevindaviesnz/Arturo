describe("executeWorkerJobWithCapabilityTimeout", () => {
  it("completes when worker finishes before timeout", async () => {
    const queued =
      enqueueJob(
        "Research AI",
        "researcher",
        {
          requiredCapabilities: [
            "research" as any,
          ],
        }
      );

    const running: Job = {
      ...queued,
      status: "running",
    };

    const result =
      await executeWorkerJobWithCapabilityTimeout(
        running,
        "llama3.2"
      );

    expect(
      result.status
    ).toBe("completed");

    expect(
      result.rawOutput
    ).toBe(
      "Generated by Ollama"
    );
  });

  it.each(["research", "email-send", "shell-execute"] as const)("fails without late completion when %s exceeds its timeout", async (capability) => {
    vi.useFakeTimers();

    vi.mocked(
      generateWithOllama
    ).mockImplementationOnce(
      () =>
        new Promise((resolve) =>
          setTimeout(
            () =>
              resolve({
                response:
                  "Too late",
              }),
            MODEL_WORK_TIMEOUT_MS * 2
          )
        ) as any
    );

    const queued =
      enqueueJob(
        "Research AI",
        "researcher",
        {
          requiredCapabilities: [
            capability,
          ],
        }
      );

    const running: Job = {
      ...queued,
      status: "running",
    };

    const promise =
      executeWorkerJobWithCapabilityTimeout(
        running,
        "llama3.2"
      );

    await vi.advanceTimersByTimeAsync(
      timeoutFor(capability) + 1
    );

    const result =
      await promise;

    expect(
      result.status
    ).toBe("failed");

    expect(
      result.error
    ).toBe(
      `Capability ${capability} timed out after ${timeoutFor(capability)}ms`
    );

    await vi.advanceTimersByTimeAsync(
      timeoutFor(capability)
    );

    expect(
      getJob(queued.id)
    ).toMatchObject({
      status: "failed",
      error:
        `Capability ${capability} timed out after ${timeoutFor(capability)}ms`,
    });
    expect(getJob(queued.id)?.output).toBeUndefined();
    expect(getJob(queued.id)?.rawOutput).toBeUndefined();
    expect(getJob(queued.id)?.completedAt).toBeUndefined();
  });
});

