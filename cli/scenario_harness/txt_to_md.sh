#!/usr/bin/env bash
# Convert a raw scenario transcript (.txt) into a readable .md:
#   - a title from the filename
#   - the console session in one fenced block
#   - strips the driver's ===> / ===NOTE / [driver] scaffolding into comments
set -euo pipefail
IN="$1"; OUT="$2"; TITLE="$3"
{
  echo "# $TITLE"
  echo
  echo "> Live transcript captured by driving \`npm run ui\` against Ollama/llama3.2 with isolated state."
  echo "> Generated by \`cli/scenario_driver.exp\`. Lines beginning \`arturo ›\` are prompts; \`◆\`/\`×\` are Arturo entries."
  echo
  echo '```console'
  # Drop driver scaffolding lines; keep the real session.
  grep -vE '^\[driver\]|^===NOTE:|^===> ' "$IN" \
    | sed -E 's/^ +$//' \
    | cat -s
  echo '```'
} > "$OUT"
